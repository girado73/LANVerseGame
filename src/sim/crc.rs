//! Multiplicative congruential checksum, identical to PHP's `crc32()`.
//!
//! PHP seeds an MCG with `~0` and multiplies by 33 per byte, *including* the
//! terminating NUL. Spawn points and teams are derived from it, so a different
//! hash would move every player's spawn.

/// The standard CRC-32 (IEEE 802.3) byte table, as PHP builds it.
static CRC32_TABLE: [u32; 256] = build_table();

const fn build_table() -> [u32; 256] {
    let mut table = [0u32; 256];
    let mut index = 0;

    while index < 256 {
        let mut value = index as u32;
        let mut bit = 0;

        while bit < 8 {
            value = if value & 1 == 1 {
                (value >> 1) ^ 0xEDB8_8320
            } else {
                value >> 1
            };
            bit += 1;
        }

        table[index] = value;
        index += 1;
    }

    table
}

/// PHP's `crc32($string)` as a signed 32-bit integer.
///
/// PHP starts from all ones and inverts the result, exactly like the standard
/// CRC-32. Unlike `crc32b`, it does *not* hash a terminating NUL.
pub fn php_crc32(bytes: &[u8]) -> i32 {
    let mut crc: u32 = 0xFFFF_FFFF;

    for byte in bytes {
        let shifted = crc >> 8;
        let index = (crc ^ u32::from(*byte)) & 0xFF;
        // PHP's lookup table is generated by the standard CRC-32 polynomial,
        // so the XOR-hash alone is not enough.
        crc = shifted ^ CRC32_TABLE[index as usize];
    }

    // PHP's crc32 is the standard CRC-32 (final XOR included), returned as a
    // signed 32-bit integer like PHP's `>i` pack.
    (!crc) as i32
}

/// `abs(crc32(id)) % modulus` with PHP's wrap-around behaviour for
/// `abs(PHP_INT_MIN)`. `modulus` must be positive.
pub fn php_crc32_index(id: &str, modulus: usize) -> usize {
    // `crc32()` is unsigned in PHP, so abs() is identity there.
    (u32::from_ne_bytes(php_crc32(id.as_bytes()).to_ne_bytes()) as u64 % modulus as u64) as usize
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_php_crc32() {
        // Verified against PHP 8.5: `printf('%u', crc32('...'))`.
        // PHP 8.5: printf('%u', crc32('123456789')) === 3421780262
        assert_eq!(php_crc32(b"123456789") as u32, 3421780262);
        assert_eq!(php_crc32(b""), 0);
        // PHP 8.5: crc32('a') === 3904355907, crc32('ab') === 2659403885.
        assert_eq!(php_crc32(b"a") as u32, 3904355907);
        assert_eq!(php_crc32(b"ab") as u32, 2659403885);
        assert_eq!(php_crc32(b"p-1"), php_crc32(b"p-1"));
    }

    #[test]
    fn spawn_index_is_unsigned_like_php() {
        // PHP: abs(crc32('p-1')) % 12 === 3.
        assert_eq!(php_crc32_index("p-1", 12), 3);
        assert_eq!(php_crc32_index("", 12), 0);
    }

    #[test]
    fn spawn_index_is_within_range() {
        for id in ["p-1", "p-2", "p-local", "p-18446744073709551615"] {
            assert!(php_crc32_index(id, 12) < 12);
            assert!(php_crc32_index(id, 2) < 2);
        }
    }
}
